export function validateKeywordContentWave(
  entries: readonly KeywordContentWaveEntry[],
  existingKeys: ReadonlySet<string>,
): void {
  const seenKeys = new Set<string>()
  const seenRelations = new Set<string>()

  for (const entry of entries) {
    if (existingKeys.has(entry.key)) {
      throw new Error(`Existing landing must be improved, not recreated: ${entry.key}`)
    }
    if (seenKeys.has(entry.key)) throw new Error(`Duplicate landing key: ${entry.key}`)
    seenKeys.add(entry.key)

    const relation = `${entry.serviceKey}:${entry.areaKey}`
    if (seenRelations.has(relation)) {
      throw new Error(`Duplicate service-area relation: ${relation}`)
    }
    seenRelations.add(relation)

    if (
      !entry.title.trim() ||
      !entry.summary.trim() ||
      !entry.localAngle.trim() ||
      entry.deliverables.length < 4 ||
      entry.process.length < 4 ||
      entry.faqs.length < 3
    ) {
      throw new Error(`Incomplete keyword landing content: ${entry.key}`)
    }
  }
}
